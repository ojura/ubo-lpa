die() {
    printf 'fatal: %s\n' "$*" >&2
    exit 1
}

note() {
    printf '[ubo-wine] %s\n' "$*"
}

prep_container() {
    # Frees disposable-container disk before a run. Everything removed is a
    # cache or regenerable metadata; package purges apply only to names supplied
    # explicitly by the operator. This function is self-contained because it
    # runs before the main script's root and APT configuration is available.
    local -a root=()
    if ((EUID != 0)); then
        command -v sudo >/dev/null || die '--prep-container requires root or sudo'
        root=(sudo)
    fi
    local before after home_dir
    before=$(df --output=avail -BM / | tail -1 | tr -dc '0-9')
    note "Container prep: ${before} MB available; clearing caches."
    # npm, pip, uv and puppeteer keep per-user caches. Sweep the active home
    # and root's home because sudo can change which one is live.
    for home_dir in "$HOME" /root; do
        [[ -d "$home_dir" ]] || continue
        rm -rf -- "$home_dir/.npm" "$home_dir/.cache/pip" \
            "$home_dir/.cache/uv" "$home_dir/.cache/puppeteer" 2>/dev/null || true
    done
    "${root[@]}" apt-get clean 2>/dev/null || true
    # APT list metadata is regenerated by the next apt-get update.
    "${root[@]}" sh -c 'rm -rf /var/lib/apt/lists/*' 2>/dev/null || true
    if [[ -n "${UBO_PREP_SWAP_MB:-}" && "${UBO_PREP_SWAP_MB}" != 0 ]]; then
        # Swap activation is kernel state and does not survive a container
        # checkpoint/restore, while the swapfile itself does; reactivate it when
        # the operator names a target. Wine-mode Chrome was OOM-killed on this
        # container class without it.
        local swap_now swap_file=/var/tmp/ubo-lpa-prep-swapfile
        swap_now=$(awk '/^SwapTotal:/ {print int($2 / 1024)}' /proc/meminfo)
        if ((swap_now >= UBO_PREP_SWAP_MB)); then
            note "Container prep: swap already at ${swap_now} MB."
        else
            note "Container prep: activating ${UBO_PREP_SWAP_MB} MB swap at $swap_file."
            if [[ ! -s "$swap_file" ]]; then
                "${root[@]}" fallocate -l "${UBO_PREP_SWAP_MB}M" "$swap_file" \
                    || die 'could not allocate the swapfile'
                "${root[@]}" chmod 600 "$swap_file"
                "${root[@]}" mkswap "$swap_file" >/dev/null \
                    || die 'mkswap failed on the prep swapfile'
            fi
            "${root[@]}" swapon "$swap_file" \
                || die 'swapon failed; this container may forbid swap'
        fi
    fi
    if [[ -n "${UBO_PREP_PURGE_PACKAGES:-}" ]]; then
        note "Container prep: purging: $UBO_PREP_PURGE_PACKAGES"
        # Word-splitting is intentional so lists and APT globs work; noglob
        # keeps the shell from expanding those globs against the CWD first.
        set -o noglob
        # shellcheck disable=SC2086
        "${root[@]}" env DEBIAN_FRONTEND=noninteractive apt-get purge -y \
            $UBO_PREP_PURGE_PACKAGES 2>&1 | tail -n 2
        set +o noglob
        "${root[@]}" env DEBIAN_FRONTEND=noninteractive \
            apt-get autoremove --purge -y 2>&1 | tail -n 1
    fi
    after=$(df --output=avail -BM / | tail -1 | tr -dc '0-9')
    note "Container prep: done; freed $((after - before)) MB (${after} MB available)."
    note 'Container prep: biggest installed packages remaining:'
    dpkg-query -W -f='${Installed-Size}\t${Package}\n' 2>/dev/null | sort -rn \
        | awk 'NR <= 12 {printf "  %6.0f MB  %s\n", $1/1024, $2}'
}

