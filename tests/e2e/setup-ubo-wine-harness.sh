reap_pid_bounded() {
    local pid=$1 i
    for i in $(seq 1 50); do
        kill -0 "$pid" >/dev/null 2>&1 || { wait "$pid" >/dev/null 2>&1 || true; return 0; }
        sleep 0.1
    done
    kill -KILL "$pid" >/dev/null 2>&1 || true
    wait "$pid" >/dev/null 2>&1 || true
}

